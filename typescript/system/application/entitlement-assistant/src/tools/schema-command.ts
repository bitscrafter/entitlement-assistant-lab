import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { PostgresClient } from "../../../../external/postgres.ts";
import { migrate, SUBSYSTEMS_IN_LAYER_ORDER } from "../database/migrate.ts";

/**
 * Writes tech-docs/data-model/schema.sql: the schema the migrations build, each table complete in one place, grouped
 * by subsystem in layer order. For reading only; the migrations are the source. Run against a PostgreSQL server it
 * may create a database on (the local one):
 *
 *   DATABASE_URL=postgres://postgres:local-development-only@localhost:54329/postgres npm run db:schema
 */
const serverUrl = process.env.DATABASE_URL;
if (serverUrl === undefined) {
  console.error("DATABASE_URL (a server where a temporary database may be created) is required.");
  process.exit(1);
}
const SYSTEM_ROOT = fileURLToPath(new URL("../../../../", import.meta.url));
const OUTPUT = fileURLToPath(new URL("../../../../../../tech-docs/data-model/schema.sql", import.meta.url));
const temporary = `schema_view_${process.pid}`;
const urlOf = (database: string) => {
  const url = new URL(serverUrl);
  url.pathname = `/${database}`;
  return url.toString();
};

/** Each subsystem's migration folder, application first, and the tables its migrations create, in creation order. */
async function tablesBySubsystem(): Promise<
  readonly { readonly name: string; readonly folder: string; readonly tables: string[] }[]
> {
  const sources = [
    { name: "application", folder: "application/entitlement-assistant/src/database/migrations" },
    ...SUBSYSTEMS_IN_LAYER_ORDER.map((name) => ({ name, folder: `subsystem/${name}/src/infra/migrations` })),
  ];
  const result = [];
  for (const source of sources) {
    const files = (await readdir(SYSTEM_ROOT + source.folder)).filter((file) => file.endsWith(".sql")).sort();
    const tables: string[] = [];
    for (const file of files) {
      const sql = await readFile(`${SYSTEM_ROOT}${source.folder}/${file}`, "utf8");
      for (const match of sql.matchAll(/CREATE TABLE (?:IF NOT EXISTS )?([a-z_]+)/gi)) {
        if (match[1] !== undefined && !tables.includes(match[1])) tables.push(match[1]);
      }
    }
    result.push({ ...source, tables });
  }
  return result;
}

const admin = new PostgresClient({ connectionString: urlOf("postgres") });
await admin.connect();
await admin.query(`CREATE DATABASE ${temporary}`);
try {
  await migrate(urlOf(temporary));
  const client = new PostgresClient({ connectionString: urlOf(temporary) });
  await client.connect();
  try {
    const lines = [
      "-- The Entitlement Assistant's database schema, generated by `npm run db:schema` from a database the migrations",
      "-- built. For reading only: the migrations are the source (application/…/database/migrations and",
      "-- subsystem/*/src/infra/migrations, applied in layer order by database/migrate.ts).",
      "",
    ];
    for (const subsystem of await tablesBySubsystem()) {
      if (subsystem.tables.length === 0) continue;
      lines.push(
        `-- ${"=".repeat(100)}`,
        `-- ${subsystem.name} · ${subsystem.folder}`,
        `-- ${"=".repeat(100)}`,
        "",
      );
      for (const table of subsystem.tables) {
        const columns = await client.query<{
          name: string;
          type: string;
          not_null: boolean;
          default_value: string | null;
        }>(
          `SELECT a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull AS not_null,
                  pg_get_expr(d.adbin, d.adrelid) AS default_value
             FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
            WHERE a.attrelid = $1::regclass AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`,
          [`public.${table}`],
        );
        const constraints = await client.query<{ name: string; definition: string }>(
          `SELECT conname AS name, pg_get_constraintdef(oid) AS definition FROM pg_constraint
            WHERE conrelid = $1::regclass
            ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'f' THEN 2 WHEN 'c' THEN 3 ELSE 4 END, conname`,
          [`public.${table}`],
        );
        const indexes = await client.query<{ definition: string }>(
          `SELECT indexdef AS definition FROM pg_indexes WHERE schemaname = 'public' AND tablename = $1
              AND indexname NOT IN (SELECT conname FROM pg_constraint WHERE conrelid = $2::regclass)
            ORDER BY indexname`,
          [table, `public.${table}`],
        );
        const grants = await client.query<{ grantee: string; privileges: string }>(
          `SELECT grantee, string_agg(privilege_type, ', ' ORDER BY privilege_type) AS privileges
             FROM information_schema.role_table_grants
            WHERE table_schema = 'public' AND table_name = $1 AND grantee <> current_user
            GROUP BY grantee ORDER BY grantee`,
          [table],
        );
        const body = [
          ...columns.rows.map(
            (column) =>
              `  ${column.name} ${column.type}${column.not_null ? " NOT NULL" : ""}${
                column.default_value === null ? "" : ` DEFAULT ${column.default_value}`
              }`,
          ),
          ...constraints.rows.map((constraint) => `  CONSTRAINT ${constraint.name} ${constraint.definition}`),
        ];
        lines.push(`CREATE TABLE ${table} (`, body.join(",\n"), ");");
        for (const index of indexes.rows) lines.push(`${index.definition.replace(/ ON public\./, " ON ")};`);
        for (const grant of grants.rows) lines.push(`-- ${grant.grantee}: ${grant.privileges}`);
        lines.push("");
      }
    }
    await writeFile(OUTPUT, `${lines.join("\n").replace(/public\./g, "")}\n`);
    console.log(`Wrote ${OUTPUT}`);
  } finally {
    await client.end();
  }
} finally {
  await admin.query(`DROP DATABASE IF EXISTS ${temporary} WITH (FORCE)`);
  await admin.end();
}
